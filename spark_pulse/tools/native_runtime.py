"""Where the Docker backend's names used to live, and still resolve (#163).

The lifecycle, the planning and the image pulls moved into
:mod:`spark_pulse.tools.backends.docker` — ``state``, ``planning``, ``images``
and ``lifecycle`` — and this module re-exports every name so that each import
of ``tools.native_runtime`` keeps working until its last importer is gone.

Re-exporting is not patching: a test that replaces a function must replace it
where it now lives (``state.publish_event``, ``lifecycle._wait_ready``), since
the moved code calls it there. The submodules reach each other as
``<module>.<name>``, so one patch reaches every caller.
"""

